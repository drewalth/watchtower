// Regenerates assets/lib/dayjsLocales.ts — a static map of string-literal dynamic
// imports, one per installed dayjs locale. Run after upgrading dayjs:
//
//   node scripts/gen-dayjs-locales.mjs
//
// Why a generated map of literals (not a runtime `import(`dayjs/locale/${x}.js`)`):
// the bundler can only code-split dynamic imports whose specifier is a static
// string. A template literal compiles to a variable-dynamic-import helper with no
// known modules, so every locale 404s at runtime. Literals each emit a real lazy
// chunk that loads on demand.

import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const names = readdirSync(resolve(root, "node_modules/dayjs/locale"))
  .filter((f) => f.endsWith(".js"))
  .map((f) => f.replace(/\.js$/, ""))
  .filter((n) => n !== "index")
  .sort();

const entries = names
  .map((n) => `  ${JSON.stringify(n)}: () => import("dayjs/locale/${n}.js"),`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-dayjs-locales.mjs — do not edit by hand.
// Regenerate after a dayjs upgrade: node scripts/gen-dayjs-locales.mjs
//
// A static map of string-literal dynamic imports, one per dayjs locale. Unlike a
// template-literal \`import(\\\`dayjs/locale/\${x}.js\\\`)\`, these literals ARE
// statically analyzable, so the bundler (rolldown/Vite) emits a real lazy chunk
// per locale instead of an empty variable-dynamic-import helper that 404s at
// runtime. initDateLocale() fetches only the viewer's locale on demand.
export const LOCALE_LOADERS: Record<string, () => Promise<unknown>> = {
${entries}
};
`;

writeFileSync(resolve(root, "assets/lib/dayjsLocales.ts"), out);
console.log(`wrote ${names.length} locale loaders to assets/lib/dayjsLocales.ts`);
